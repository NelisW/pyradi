"""
check_urls.py — URL liveness checker for the pyradi source tree.

Run from the pyradi conda environment on Windows:
    conda run -n pyradi python pyradi/check_urls.py

Or from inside the pyradi/ folder:
    python check_urls.py

Produces:  dev/staleURLs.md   (written in the dev/ folder next to this script)
"""

import re
import sys
import time
import pathlib
import urllib.request
import urllib.error
import socket
import ssl
from collections import defaultdict

ROOT = pathlib.Path(__file__).parent.parent   # …/pyradi/pyradi/pyradi
EXTENSIONS = {".py", ".rst", ".md"}
EXCLUDE_DIRS = {".ipynb_checkpoints", "__pycache__", ".git"}

URL_RE = re.compile(r'https?://[^\s\)\]\"\x27<>`,;\\]+')

# ---------------------------------------------------------------------------
# 1. Collect all URL occurrences
# ---------------------------------------------------------------------------
def collect_urls(root: pathlib.Path):
    """Return list of (rel_path, lineno, url)."""
    records = []
    for path in sorted(root.rglob("*")):
        if not path.is_file():
            continue
        if path.suffix not in EXTENSIONS:
            continue
        if any(ex in path.parts for ex in EXCLUDE_DIRS):
            continue
        try:
            text = path.read_text(encoding="utf-8", errors="replace")
        except Exception:
            continue
        for lineno, line in enumerate(text.splitlines(), 1):
            for url in URL_RE.findall(line):
                # Strip common trailing punctuation that isn't part of the URL
                url = re.sub(r'[.,;:!?)\]>]+$', '', url)
                records.append((path, lineno, url))
    return records


# ---------------------------------------------------------------------------
# 2. Test a URL — returns (int_status_or_str, final_url_after_redirects)
# ---------------------------------------------------------------------------
CTX = ssl.create_default_context()
CTX.check_hostname = False
CTX.verify_mode = ssl.CERT_NONE

HEADERS = {
    "User-Agent": (
        "Mozilla/5.0 (Windows NT 10.0; Win64; x64) "
        "AppleWebKit/537.36 (KHTML, like Gecko) "
        "Chrome/124.0.0.0 Safari/537.36"
    ),
    "Accept": "text/html,application/xhtml+xml,*/*;q=0.8",
    "Accept-Language": "en-US,en;q=0.9",
}


def probe(url: str, timeout: int = 15) -> tuple:
    """Return (status_code_or_error_str, final_url)."""
    # Skip placeholder/template URLs
    if "username:password" in url or "proxyname" in url:
        return "SKIP", url

    for method in ("HEAD", "GET"):
        try:
            req = urllib.request.Request(url, headers=HEADERS, method=method)
            with urllib.request.urlopen(req, timeout=timeout, context=CTX) as r:
                return r.status, r.url
        except urllib.error.HTTPError as e:
            if method == "HEAD" and e.code in (405, 406, 501):
                continue          # retry with GET
            return e.code, url
        except urllib.error.URLError as e:
            return f"ERR:{e.reason}", url
        except socket.timeout:
            return "TIMEOUT", url
        except Exception as e:
            return f"ERR:{type(e).__name__}:{e}", url
    return "ERR:no-method-succeeded", url


def is_ok(status) -> bool:
    return isinstance(status, int) and status < 400


# ---------------------------------------------------------------------------
# 3. Main
# ---------------------------------------------------------------------------
def main():
    print(f"Scanning {ROOT} …")
    records = collect_urls(ROOT)

    # Group occurrences by URL
    url_locs: dict[str, list] = defaultdict(list)
    for path, lineno, url in records:
        url_locs[url].append((path, lineno))

    unique = list(url_locs.items())
    print(f"Found {len(records)} URL occurrences → {len(unique)} unique URLs to test.\n")

    results = {}   # url -> (status, final_url, locs)
    for i, (url, locs) in enumerate(unique, 1):
        status, final_url = probe(url)
        tag = "OK  " if is_ok(status) else ("SKIP" if status == "SKIP" else "FAIL")
        print(f"[{i:3d}/{len(unique)}] {tag}  {status!s:<25}  {url}")
        results[url] = (status, final_url, locs)
        time.sleep(0.15)   # be polite

    # ---------------------------------------------------------------------------
    # 4. Write staleURLs.md
    # ---------------------------------------------------------------------------
    stale = {
        url: (status, final_url, locs)
        for url, (status, final_url, locs) in results.items()
        if not is_ok(status) and status != "SKIP"
    }

    out_path = pathlib.Path(__file__).parent / "staleURLs.md"
    with out_path.open("w", encoding="utf-8") as f:
        f.write("# Stale / Unreachable URLs\n\n")
        f.write(f"_Generated by `check_urls.py` on {time.strftime('%Y-%m-%d')}_\n\n")
        f.write(
            f"Tested {len(unique)} unique URLs across `*.py`, `*.rst`, and `*.md` files.  \n"
            f"**{len(stale)}** URLs returned a non-2xx/3xx status or a connection error.  \n"
            f"Placeholder/template URLs (e.g. `username:password@proxyname`) are excluded.\n\n"
        )
        f.write("| File | Line | Status | URL |\n")
        f.write("|------|------|--------|-----|\n")

        for url, (status, final_url, locs) in sorted(
            stale.items(), key=lambda x: (str(x[1][2][0][0]), x[1][2][0][1])
        ):
            for path, lineno in locs:
                rel = path.relative_to(ROOT)
                f.write(f"| `{rel}` | {lineno} | `{status}` | {url} |\n")

    print(f"\n{'='*70}")
    print(f"  {len(stale)} stale URLs written to: {out_path}")
    print(f"{'='*70}\n")

    # Also print a summary to stdout
    ok_count  = sum(1 for u, (s, _, __) in results.items() if is_ok(s))
    skip_count = sum(1 for u, (s, _, __) in results.items() if s == "SKIP")
    print(f"  OK:   {ok_count}")
    print(f"  FAIL: {len(stale)}")
    print(f"  SKIP: {skip_count}  (placeholder URLs)\n")


if __name__ == "__main__":
    main()
